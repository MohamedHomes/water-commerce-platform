export type AdminLanguage = 'en' | 'ar';

export function loadAdminLanguage(read: (key: string) => string | null): AdminLanguage {
    return read('aquaflow-admin-language') === 'ar' ? 'ar' : 'en';
}

export function syncAdminLanguage(
    language: AdminLanguage,
    write: (key: string, value: string) => void,
    documentElement: Pick<HTMLElement, 'lang' | 'dir'>,
): void {
    write('aquaflow-admin-language', language);
    documentElement.lang = language;
    documentElement.dir = language === 'ar' ? 'rtl' : 'ltr';
}

