export type AdminMessage = keyof typeof messages.en;

export function translate(language: AdminLanguage, key: AdminMessage): string {
    return messages[language][key];
}

export function formatMessage(
    language: AdminLanguage,
    key: AdminMessage,
    values: Record<string, string | number>,
): string {
    return translate(language, key).replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ''));
}

export function translateStatus(language: AdminLanguage, value: string): string {
    const keyByValue: Record<string, AdminMessage> = {
        payment_pending: 'orderStatusPendingPayment',
        payment_failed: 'orderStatusPaymentFailed',
        placed: 'orderStatusPlaced',
        paid: 'orderStatusPaid',
        confirmed: 'orderStatusConfirmed',
        cancelled: 'orderStatusCancelled',
        delivered: 'orderStatusDelivered',
        card: 'paymentCard',
        cash: 'paymentCash',
        pending_dispatch: 'deliveryPendingDispatch',
        assigned: 'deliveryAssigned',
        picked_up: 'deliveryPickedUp',
        failed: 'deliveryFailed',
        in_stock: 'availabilityAvailable',
        low_stock: 'availabilityLowStock',
        out_of_stock: 'availabilityOutOfStock',
        unavailable: 'availabilityUnavailable',
    };
    const key = keyByValue[value];
    return key ? translate(language, key) : value.replace(/_/g, ' ');
}

export function translateError(language: AdminLanguage, message: string): string {
    const exact: Record<string, AdminMessage> = {
        'Inventory adjustment must be non-zero': 'inventoryDeltaInvalid',
        'Product not found': 'productNotFound',
        'Inventory cannot be reduced below zero': 'inventoryBelowZero',
        'Delivery not found': 'deliveryNotFound',
        'Pending review not found': 'reviewNotFound',
        'At least one product field must be updated': 'productUpdateEmpty',
        'Percentage discounts cannot exceed 100': 'percentageTooHigh',
        'Promotion end date must be after its start date': 'promotionDatesInvalid',
        'Promotion code already exists': 'promotionExists',
        'Promotion not found': 'promotionNotFound',
        'Administrator access required': 'adminRequired',
        'Invalid email or password': 'loginFailed',
        'This account is not authorized for administration': 'notAuthorized',
    };
    const key = exact[message];
    if (key) return translate(language, key);
    const transition = /^Delivery cannot transition from (.+) to (.+)$/.exec(message);
    if (transition) {
        return formatMessage(language, 'deliveryTransitionInvalid', {
            current: translateStatus(language, transition[1]),
            next: translateStatus(language, transition[2]),
        });
    }
    return message;
}
